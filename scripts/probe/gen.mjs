// Task-set generator for holdout probes — the generator replaces
// hand-designed sets. Its code is frozen (committed) BEFORE a set is drawn;
// each acceptance round draws a fresh seed.
//
//   node scripts/probe/gen.mjs --seed=42            # emit tasks-p0r3.js + spec
//   node scripts/probe/gen.mjs --seed=42 --check    # draw + structural check
//
// Per-seed draws:
//   * world anchor at distance ≥45 from the origin, floor level and terrain
//     archetype (坐标远离原点 / 物品 / 地形 / 种子)
//   * 10 kinds per level from the template pools (ids 81–110)
//   * every parameter resolved and baked into the emitted file, so the drawn
//     set is auditable data, not code that silently re-samples.

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { POOLS, kindsOf, sampleFor } from './gen-library.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const args = Object.fromEntries(process.argv.slice(2).map(a => {
  const [k, v] = a.replace(/^--/, '').split('=');
  return [k, v ?? true];
}));

// ---- mulberry32 --------------------------------------------------------------

function rng(seed) {
  let s = seed >>> 0;
  const next = () => {
    s = (s + 0x6D2B79F5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  const r = () => next();
  r.int = (a, b) => a + Math.floor(next() * (b - a + 1));
  r.pick = arr => arr[Math.floor(next() * arr.length)];
  r.bool = () => next() < 0.5;
  r.pick2 = arr => {
    const i = Math.floor(next() * arr.length);
    let j = Math.floor(next() * (arr.length - 1));
    if (j >= i) j++;
    return [arr[i], arr[j]];
  };
  r.shuffle = arr => {
    const a = arr.slice();
    for (let i = a.length - 1; i > 0; i--) {
      const j = Math.floor(next() * (i + 1));
      [a[i], a[j]] = [a[j], a[i]];
    }
    return a;
  };
  return r;
}

// ---- draw --------------------------------------------------------------------

const LEVELS = ['L1', 'L2', 'L3'];
const PER_LEVEL = 10;
const FIRST_ID = 81;

const HALF = 13; // slab half-width — recenter_find needs ore >16 blocks out,
// and every task object keeps |offset| ≤ half−2 so the her-side approach
// column always lands on the slab.

function drawWorld(r) {
  // Anchor inside the 64³ world with the slab margins clear, at least 45
  // blocks from the origin — the P3 deferAmbit bug only surfaced past 32.
  let ax, az;
  do {
    ax = r.int(HALF + 1, 63 - HALF - 1);
    az = r.int(HALF + 1, 63 - HALF - 1);
  } while (Math.hypot(ax, az) < 45);
  return { terrain: r.pick(POOLS.terrains), ax, az, fy: r.int(1, 4), floor: r.pick(POOLS.floors), half: HALF };
}

export function drawTasks(seed) {
  const r = rng(seed);
  const world = drawWorld(r);
  const tasks = [];
  let id = FIRST_ID;
  for (const level of LEVELS) {
    const kinds = r.shuffle(kindsOf(level)).slice(0, PER_LEVEL);
    for (const kind of kinds) {
      const params = sampleFor(kind, r, world);
      tasks.push({ kind, spec: { ...params, id: id++, level, world } });
    }
  }
  return { seed, world, tasks };
}

// ---- emit ---------------------------------------------------------------------

function emit(draw) {
  const lines = [];
  lines.push(`// GENERATED by scripts/probe/gen.mjs --seed=${draw.seed} on ${new Date().toISOString()}`);
  lines.push(`// One-shot holdout set (规则一.7 一次性集): measure once, then retire.`);
  lines.push(`// World: ${draw.world.terrain} anchored at (${draw.world.ax}, fy=${draw.world.fy}, ${draw.world.az}),`);
  lines.push(`// floor ${draw.world.floor} — anchor ${Math.hypot(draw.world.ax, draw.world.az).toFixed(1)} blocks from origin.`);
  lines.push(`// Specs are frozen draws — do not hand-edit; redraw with a new seed.`);
  lines.push(`import { build } from './gen-library.mjs';`);
  lines.push('');
  lines.push('export const TASKS = [');
  for (const { kind, spec } of draw.tasks) {
    lines.push(`  build(${JSON.stringify(kind)}, ${JSON.stringify(spec)}),`);
  }
  lines.push('];');
  lines.push('');
  return lines.join('\n');
}

// ---- CLI ----------------------------------------------------------------------

const seed = args.seed === undefined ? null : Number(args.seed);
if (seed === null || !Number.isInteger(seed) || seed < 0) {
  console.error('usage: node scripts/probe/gen.mjs --seed=<int> [--check] [--out=<file>]');
  process.exit(2);
}

const draw = drawTasks(seed);
const outFile = join(HERE, String(args.out ?? 'tasks-p0r3.js'));
writeFileSync(outFile, emit(draw), 'utf8');
console.log(`seed=${seed} world=${draw.world.terrain}@(${draw.world.ax},fy${draw.world.fy},${draw.world.az}) → ${outFile}`);
console.log(`tasks: ${draw.tasks.map(t => `${t.spec.id}:${t.kind}`).join(' ')}`);

if (args.check) {
  const { TASKS } = await import(`./tasks-p0r3.js?seed=${seed}`);
  const seen = new Set();
  let bad = 0;
  for (const t of TASKS) {
    const missing = ['id', 'level', 'title', 'description', 'setup', 'success', 'candidates', 'reference']
      .filter(k => t[k] === undefined);
    if (missing.length) { console.error(`T${t.id} missing: ${missing}`); bad++; }
    if (seen.has(t.id)) { console.error(`duplicate id ${t.id}`); bad++; }
    seen.add(t.id);
  }
  const byLevel = {};
  for (const t of TASKS) byLevel[t.level] = (byLevel[t.level] ?? 0) + 1;
  console.log(`check: ${TASKS.length} tasks, levels ${JSON.stringify(byLevel)}, ${bad === 0 ? 'OK' : `${bad} bad`}`);
  process.exit(bad === 0 ? 0 : 1);
}
